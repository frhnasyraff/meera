const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const config = JSON.parse(fs.readFileSync(path.join(root, 'private-access.json'), 'utf8'));
const emails = [...new Set(config.allowedEmails.map(email => email.trim().toLowerCase()))];
if (emails.length > 2 || emails.some(email => !/^[a-z0-9.!#$%&'*+\/=?^_`{|}~-]+@[a-z0-9.-]+\.[a-z]{2,}$/.test(email))) {
  throw new Error('Set at most two valid email addresses in private-access.json.');
}
const hashes = emails.map(email => createHash('sha256').update(email).digest('hex').toUpperCase());
fs.writeFileSync(path.join(root, 'private-access.js'), `// Generated by scripts/build-private-access.cjs.\nwindow.PRIVATE_GALLERY_EMAIL_HASHES = Object.freeze(${JSON.stringify(hashes)});\n`);
fs.writeFileSync(path.join(root, 'firestore.rules'), `rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {
    function isAllowedAccount() {
      return request.auth != null
        && request.auth.token.email_verified == true
        && request.auth.token.firebase.sign_in_provider == 'google.com'
        && hashing.sha256(request.auth.token.email.lower().toUtf8()).toHexString() in ${JSON.stringify(hashes)};
    }
    match /{collectionName}/{documentId} {
      allow read, write: if collectionName in ['albums', 'photos', 'trips', 'songs']
        && isAllowedAccount();
    }
  }
}
`);
console.log(`Private access files generated for ${emails.length} account(s).`);
